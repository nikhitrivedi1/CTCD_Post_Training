"""Formatting (synthetic) dataset handler.

Synthetic dataset generated by scripts/data/generate_formatting_data.py.
Contains document page images with formatting-rich markdown ground truth
(bold, italic, strikethrough).

Pipeline: generate (if missing) -> load from category subdirs.
"""

import logging
import subprocess
import sys
from pathlib import Path

from datasets import Dataset
from PIL import Image

from .base import DatasetHandler

logger = logging.getLogger(__name__)


class FormattingHandler(DatasetHandler):
    """Handler for synthetic formatting data.

    prepare() invokes the generator if the target directory is missing.
    load() walks the category subdirectories and pairs images with markdown GT.
    """

    def prepare(
        self,
        data_dir: str,
        num_pages: int = 200,
        categories: str = "all",
        eval_frac: float = 0.1,
        augment: bool = True,
        seed: int = 42,
        **kwargs,
    ) -> None:
        """Generate synthetic formatting data if not already present.

        Args:
            data_dir: Output directory for generated data.
            num_pages: Pages per category.
            categories: Comma-separated category list or "all".
            eval_frac: Fraction held out for eval.
            augment: Apply image augmentations.
            seed: Random seed for reproducibility.
        """
        data_path = Path(data_dir)

        # Check if data already exists (any category subdir with images)
        if data_path.exists():
            has_images = any(data_path.rglob("images/*.png"))
            if has_images:
                logger.info(f"Formatting data already exists at {data_dir}, skipping generation")
                return

        logger.info(f"Generating synthetic formatting data at {data_dir}...")

        # Find the generator script
        script = Path(__file__).resolve().parents[3] / "scripts" / "data" / "formatting_generator.py"
        if not script.exists():
            raise FileNotFoundError(f"Generator script not found: {script}")

        cmd = [
            sys.executable, str(script),
            "--output_dir", str(data_dir),
            "--num_pages", str(num_pages),
            "--categories", categories,
            "--eval_frac", str(eval_frac),
            "--seed", str(seed),
        ]
        if augment:
            cmd.append("--augment")

        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            logger.error(f"Generator failed:\n{result.stderr}")
            raise RuntimeError(f"Formatting data generation failed: {result.stderr[:500]}")

        logger.info("Generation complete")

    def validate(self, data_dir: str) -> dict:
        """Check that category dirs have matched image/markdown pairs.

        Args:
            data_dir: Root directory with category subdirs.

        Returns:
            Validation results dict.
        """
        data_path = Path(data_dir)
        if not data_path.exists():
            return {"ok": False, "details": f"Directory not found: {data_dir}"}

        total_images = 0
        total_markdown = 0
        total_matched = 0
        categories_found = []

        for category_dir in sorted(data_path.iterdir()):
            if not category_dir.is_dir():
                continue
            categories_found.append(category_dir.name)

            for split in ("train", "eval"):
                images_dir = category_dir / split / "images"
                markdown_dir = category_dir / split / "markdown"
                if not images_dir.exists():
                    continue

                images = list(images_dir.glob("*.png"))
                md_files = list(markdown_dir.glob("*.md")) if markdown_dir.exists() else []
                total_images += len(images)
                total_markdown += len(md_files)

                img_stems = {p.stem for p in images}
                md_stems = {p.stem for p in md_files}
                total_matched += len(img_stems & md_stems)

        result = {
            "ok": total_matched > 0 and total_matched == total_images,
            "categories": len(categories_found),
            "images": total_images,
            "markdown": total_markdown,
            "matched": total_matched,
            "details": f"{len(categories_found)} categories, {total_matched} matched pairs",
        }
        return result

    def load(
        self,
        data_dir: str,
        max_train_samples: int | None = None,
        eval_fraction: float = 0.1,
        **kwargs,
    ) -> tuple[Dataset, Dataset | None]:
        """Load image + markdown pairs from category subdirectories.

        Walks the standard structure:
            {data_dir}/{category}/{split}/images/*.png
            {data_dir}/{category}/{split}/markdown/*.md

        Args:
            data_dir: Root directory with category subdirs.
            max_train_samples: Cap on training samples.
            eval_fraction: Not used (data is pre-split by generator).

        Returns:
            Tuple of (train_dataset, eval_dataset).
        """
        data_path = Path(data_dir)
        if not data_path.exists():
            raise FileNotFoundError(f"Data not found at {data_dir}. Run: prepare.py --dataset formatting")

        train_samples = []
        eval_samples = []

        for category_dir in sorted(data_path.iterdir()):
            if not category_dir.is_dir():
                continue

            for split, target in [("train", train_samples), ("eval", eval_samples)]:
                images_dir = category_dir / split / "images"
                markdown_dir = category_dir / split / "markdown"
                if not images_dir.exists():
                    continue

                for img_path in sorted(images_dir.glob("*.png")):
                    md_path = markdown_dir / (img_path.stem + ".md")
                    if not md_path.exists():
                        continue

                    with open(md_path) as f:
                        ground_truth = f.read().strip()
                    if not ground_truth:
                        continue

                    with Image.open(img_path) as im:
                        image = im.convert("RGB")
                        image.load()

                    target.append({"image": image, "ground_truth": ground_truth})

        if not train_samples:
            raise ValueError(f"No valid training samples found in {data_dir}")

        train_dataset = Dataset.from_list(train_samples)
        eval_dataset = Dataset.from_list(eval_samples) if eval_samples else None

        if max_train_samples and len(train_dataset) > max_train_samples:
            train_dataset = train_dataset.select(range(max_train_samples))

        eval_count = len(eval_dataset) if eval_dataset else 0
        logger.info(f"Formatting: {len(train_dataset)} train, {eval_count} eval")
        return train_dataset, eval_dataset
